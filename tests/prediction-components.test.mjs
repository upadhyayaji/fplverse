import assert from "node:assert/strict";
import {predictPlayerBreakdown as model,poissonExpectation,COMPONENTS} from "../assets/predictions.mjs";
import {actualComponents,makeSnapshot,evaluateSnapshot} from "../scripts/prediction-audit.mjs";
const fixture={id:11,event:5,team_h:1,team_a:2,team_h_difficulty:3,team_a_difficulty:3};
const player={id:1,web_name:"Test",team:1,element_type:2,minutes:360,starts:4,status:"a",chance_of_playing_next_round:null,expected_goals:".3",expected_assists:".4",defensive_contribution:42,bonus:2};
const run=(changes={},fixtures=[fixture])=>model({player:{...player,...changes},fixtures,gameweek:5,completedGameweeks:4});
const single=run();
assert.equal(single.total,Math.round(Object.values(single.components).reduce((s,n)=>s+n,0)*10)/10);
assert.deepEqual(run({},[]).components,Object.fromEntries(COMPONENTS.map(k=>[k,0])));
assert.equal(run({chance_of_playing_next_round:0}).total,0);
for(const key of COMPONENTS) assert.ok(Math.abs(run({chance_of_playing_next_round:50}).components[key]-single.components[key]/2)<1e-10);
const double=run({},[fixture,{...fixture,id:12}]);
for(const key of COMPONENTS) assert.ok(Math.abs(double.components[key]-2*single.components[key])<1e-10);
assert.ok(run({expected_goals:3}).components.goals>single.components.goals);
assert.ok(run({expected_assists:3}).components.assists>single.components.assists);
assert.ok(run({defensive_contribution:80}).components.defensiveContributions>single.components.defensiveContributions);
assert.ok(single.components.defensiveContributions<=2);
assert.equal(run({element_type:1}).components.defensiveContributions,0);
assert.equal(run({element_type:4}).components.cleanSheets,0);
assert.equal(single.components.saves,0);
assert.ok(run({element_type:1,saves:30}).components.saves>run({element_type:1,saves:5}).components.saves);
assert.ok(run({yellow_cards:5}).components.yellowCards<single.components.yellowCards);
assert.ok(run({minutes:30,starts:0}).components.appearance<single.components.appearance);
assert.ok(run({}).fixtures[0].expectedMinutes<=90);
assert.ok(run({expected_goals:null,expected_assists:undefined}).total>0);
assert.ok(Math.abs(poissonExpectation(2,k=>k)-2)<1e-10);
assert.ok(Math.abs(poissonExpectation(2,k=>k===0?1:0)-Math.exp(-2))<1e-10);
assert.ok(poissonExpectation(2,k=>Math.floor(k/3))>0,"saves threshold expectation must not be floor(mean/3)");
const past={...fixture,id:1,event:1,finished:true,team_h_score:3,team_a_score:0};
assert.equal(run({},[past,fixture]).fixtures[0].environment.source,"smoothed team goals");
assert.deepEqual(run({},[fixture,{...past,event:6}]),single,"future outcomes cannot adjust opponent strength");
const record={stats:{total_points:6},explain:[{fixture:1,stats:[{identifier:"minutes",points:2},{identifier:"defensive_contribution",points:2}]},{fixture:2,stats:[{identifier:"minutes",points:2}]}]};
assert.equal(actualComponents(record).appearance,4);
assert.equal(actualComponents(record).defensiveContributions,2);
assert.equal(actualComponents({...record,stats:{total_points:7}}),null);
assert.equal(actualComponents({stats:{total_points:0}}),null);
const snapshot=makeSnapshot({events:[{id:1,deadline_time:"2026-08-15T10:00:00Z",finished:true},{id:5,deadline_time:"2026-09-18T10:00:00Z",finished:false}],elements:[player]},[past,fixture],"2026-09-17T12:00:00Z","hash");
assert.equal(snapshot.modelVersion,"components-v2");
assert.ok(Number.isFinite(snapshot.players[0].comparison));
assert.equal(snapshot.fixtures.length,2);
const scored=evaluateSnapshot(snapshot,{id:5,finished:true,data_checked:true},{elements:[{id:1,...record,stats:{total_points:6,minutes:180}}]},"now");
assert.equal(scored.comparison.count,1);
assert.equal(scored.components.appearance.count,1);
assert.equal(scored.rows[0].actualComponents.appearance,4);
const legacy=structuredClone(snapshot);delete legacy.players[0].components;delete legacy.players[0].comparison;
const old=evaluateSnapshot(legacy,{id:5,finished:true,data_checked:true},{elements:[{id:1,stats:{minutes:90,total_points:2}}]},"now");
assert.equal(old.comparison,null);assert.equal(old.components.goals,null);
console.log("Component tests passed: minutes, positions, probability thresholds, opponents, doubles, explanations, v1 comparisons and old archives.");
